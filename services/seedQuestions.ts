/** 供 QuestionBoard 使用：把种子转成可入库的初始记录 */
export interface SeedVQuestion {
  id: string;
  text: string;
  createdAt: number;
  upvotes: number;
  category?: string;
}

export function buildSeedQuestions(): SeedVQuestion[] {
  const base = Date.now();
  // 稍微打散，让「最新」排序不至于完全按数组顺序；给一点随机初始热度
  return SEED_QUESTIONS.map((q, i) => ({
    id: `seed-${i}-${Math.random().toString(36).slice(2, 8)}`,
    text: q.text,
    category: q.category,
    createdAt: base - i * 1000, // 越靠前的越「新」
    upvotes: Math.floor(Math.random() * 12),
  }));
}
