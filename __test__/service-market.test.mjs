  await assert.rejects(f.market.action(buyer, o.id, { revision: o.revision, action: 'complete', note: 'not delivered' }));
  await assert.rejects(f.market.action(seller, o.id, { revision: o.revision, action: 'deliver', summary: 'result', source: 'javascript:alert(1)', limitation: 'test' }));
