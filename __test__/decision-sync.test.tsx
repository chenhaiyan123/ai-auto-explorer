import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import assert from 'node:assert/strict';
import DecisionSync from '../components/DecisionSync';
import {decisionDelta} from '../services/decisionSync';
import {collectWaits, heartbeatAction, waitEvidenceCurrent} from '../services/problemHeartbeat';
import {decisionFixture} from './decision-sync.fixture';
let s=decisionFixture();const w=s.problemHeartbeat!.waits[1];
const baseline=decisionDelta(s).baseline!.at;
s=heartbeatAction(s,{action:'read',ids:s.problemHeartbeat!.updates.map(u=>u.id)},baseline+9000,()=> 'read');
assert.equal(decisionDelta(s).baseline!.at,baseline);
assert.equal(decisionDelta(s).changes.length,1);
let html=renderToStaticMarkup(<DecisionSync state={s} wait={w}/>);
for(const phrase of ['上次决策后','为什么需要你','建议怎么做','依据 → 推理','先做三天','额外费用未报价']) assert.ok(html.includes(phrase));
assert.equal(waitEvidenceCurrent(s,w),true);
const changed=structuredClone(s);changed.context.facts[0].excerpt='修订数据';
assert.equal(waitEvidenceCurrent(changed,w),false);
assert.throws(()=>heartbeatAction(changed,{action:'reply',id:w.id,decision:'approve',answer:'同意'},baseline+10000,()=> 'x'));
assert.doesNotThrow(()=>heartbeatAction(changed,{action:'reply',id:w.id,decision:'decline',answer:'先核验'},baseline+10000,()=> 'x'));
html=renderToStaticMarkup(<DecisionSync state={changed} wait={w}/>);assert.match(html,/暂不批准旧建议/);
const legacy={...w,decisionBrief:undefined};html=renderToStaticMarkup(<DecisionSync state={s} wait={legacy}/>);assert.match(html,/没有记录具体建议/);assert.match(html,/没有关联已核验事实/);
assert.throws(()=>collectWaits(s,[{...w,title:'新请求',condition:'新条件',decisionBrief:{...w.decisionBrief,evidenceIds:['fake']}}],baseline+20000,()=> 'bad'));
const empty=structuredClone(s);empty.problemHeartbeat!.waits=[];empty.problemHeartbeat!.judgments=[];assert.equal(decisionDelta(empty).baseline,undefined);
console.log('Decision sync: decision baseline, read isolation, exact evidence recheck, rejection, missing evidence and legacy fallback passed.');
